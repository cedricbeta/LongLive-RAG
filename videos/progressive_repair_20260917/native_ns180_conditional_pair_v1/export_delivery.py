#!/usr/bin/env python3
"""Publish complete candidate video, raw calls, masks, failure and cost records."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import shutil

p = argparse.ArgumentParser()
p.add_argument('--target', type=Path, required=True)
a = p.parse_args()
root, target = Path(__file__).resolve().parent, a.target.resolve()
read = lambda p: json.loads(p.read_text())
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
summary = read(root / 'summary.json')
assert summary['status'] == 'closed_one_rejected_candidate_then_resource_interruption'
assert read(root / 'queue_status.json')['status'] == 'completed'
for kind in ['results', 'artifacts']:
    assert not (target / kind / root.name).exists()
calls = sorted(root.glob('*/run/vlm_cache/*/*.json'))
required = {Path(x).resolve() for source in calls for x in read(source)['ordered_image_paths']}
actual_inputs = len(required)
required.update(p.resolve() for p in root.glob('*/run/backend/frames/**/*.png'))
required.update(p.resolve() for p in (root / 'reviews').glob('**/*.png'))
files, paths, omitted = {}, [], []


def bind(path):
    key = str(path.relative_to(target))
    assert key not in files
    files[key] = {'sha256': sha(path), 'bytes': path.stat().st_size}
    paths.append(key)


def destination(source):
    return target / ('artifacts' if source.suffix == '.mp4' or 'reviews' in source.relative_to(root).parts and source.suffix == '.png' else 'results') / root.name / source.relative_to(root)


for source in sorted(root.rglob('*')):
    if not source.is_file() or '__pycache__' in source.parts or '.call_locks' in source.parts or source.suffix == '.lock':
        continue
    if source.name.startswith('latents_') or source.suffix in ['.png', '.jpg'] and source.resolve() not in required:
        omitted.append({'path': str(source.relative_to(root)), 'bytes': source.stat().st_size, 'sha256': sha(source)})
        continue
    assert source.suffix in ['.py', '.json', '.jsonl', '.yaml', '.txt', '.log', '.pid', '.png', '.jpg', '.pt', '.mp4'] or source.name in ['STOP', 'EXITED'], source
    assert source.stat().st_size < 50 * 1024**2, source
    if source.suffix in ['.json', '.jsonl', '.txt', '.log']:
        assert not re.search(r'\bhf_[A-Za-z0-9]{20,}|X-Amz-(?:Signature|Credential)=|Authorization: Bearer ', source.read_text()), source
    dest = destination(source)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, dest)
    bind(dest)
for source in required:
    assert destination(source).is_file()
dest = target / 'results' / root.name / 'omitted_derived_files.json'
dest.write_text(json.dumps({'reason': 'Latents are regenerated by the pinned generation entry; redundant decoded frames are recoverable from the exact published videos. Every actual VLM input, backend evidence frame, mask option, candidate video and fixed review view is included.', 'files': omitted}, indent=2) + '\n')
bind(dest)
review_name = 'feedback_candidate_0001_shot00_attempt1'
page = '''<!doctype html><html lang="zh"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>ns180 自动修复：完整候选未通过，后续资源中断</title>
<style>body{font:17px/1.7 system-ui;max-width:1150px;margin:30px auto;padding:0 20px}video{width:100%}.sheet{width:100%}.inputs{display:flex;gap:12px;flex-wrap:wrap}.inputs img{max-width:31%;object-fit:contain}pre{white-space:pre-wrap;overflow-wrap:anywhere;background:#f3f4f6;padding:16px}summary{cursor:pointer}</style>
<h1>ns180：自动候选未通过，本组已关闭</h1>
<p>官方 LongLive-RAG 1.3B 原片；程序自动诊断、定位并尝试修复首个 10 秒窗口的 Noah 剃头要求。一个完整候选被拒绝，原片按未解决交付，保留改进为零。第二次生成遇到其他会话占用 GPU 0 后中断；固定噪声组未通过空闲检查。本页不是完成的成对策略比较。</p>
<p><a href="../../reproduction/native_ns180_conditional_pair/README.md">成本与复现</a> · <a href="../../results/native_ns180_conditional_pair_v1/summary.json">实际结果</a> · <a href="../native_development_pilot12_batch6_v1/ns180/baseline/videos/rank0-0-0_lora.mp4">精确原片</a> · <a href="feedback/run/backend/candidate_0001_shot00_attempt1/videos/rank0-0-0_lora.mp4">精确候选</a></p>
<video controls preload="metadata" src="reviews/feedback_candidate_0001_shot00_attempt1/full_60s_comparison.mp4"></video>
<p>完整 60 秒、960 帧，左为原片，右为自动候选。首段只是局部剃短，仍有发圈与不规则发块；35–50 秒候选多处保留短卷发，原片同期多处已自然出现剃头。衣服仍偏蓝，动作、道具、背景和碎片伪影也改变。最后剃头已在原片出现，不能计为修复收益。以下是开发者固定帧观察，无独立验收、人评或连续运动结论。</p>
<p>检查器也有问题：原片第三个角色分配按外观错误地标为 absent；它先把偏蓝衣服判为深绿，随后把相似衣服判为失败。身高与 work detail 判断也不可靠。原始结果全部保留，不能把其“退化”标签直接当视觉真值。</p>
<h2>全部 18 个固定时点</h2>
'''
for i in [1, 2, 3]:
    page += f'<img class="sheet" alt="完整固定时点对照 {i}" src="reviews/{review_name}/fixed_views_{i}.png">'
page += '<p>首个生成 591.559 秒；中断生成 27.776 秒。反馈 worker 1147.220 秒，含启动清理的生命周期 1185.559 秒；固定噪声空闲检查 20.518 秒，队列共 1208.437 秒。22 次真实模型调用。嵌套阶段不能相加；GPU 0 末段能耗包含其他会话作业。两个预算均已关闭。</p><h2>全部实际模型输入与原始响应</h2>'
gallery_parent = target / 'artifacts' / root.name
import os
for source in calls:
    call = read(source)
    page += '<details><summary>' + html.escape(call['call_kind'] + ' · ' + source.stem[:12]) + '</summary><div class="inputs">'
    for path in call['ordered_image_paths']:
        dest = destination(Path(path).resolve())
        page += '<a href="' + html.escape(os.path.relpath(dest, gallery_parent)) + '"><img alt="实际模型输入" src="' + html.escape(os.path.relpath(dest, gallery_parent)) + '"></a>'
    page += '</div><p><a href="' + html.escape(os.path.relpath(destination(source), gallery_parent)) + '">完整原始调用 JSON</a></p><pre>' + html.escape(json.dumps({k: v for k, v in call.items() if k not in ['ordered_image_paths']}, ensure_ascii=False, indent=2)) + '</pre></details>'
page += '<p>真实自动尝试；未使用人工 mask 或固定目标绕过 guard。首个候选被拒绝，第二个缩小区域的动作没有完整视频可评。没有重启、追加窗口或检查器调参；本次失败不被隐藏。</p></html>\n'
dest = target / 'artifacts' / root.name / 'index.html'
dest.write_text(page)
bind(dest)
bind(target / 'reproduction/native_ns180_conditional_pair/README.md')
parent = target / 'artifacts/native_development_pilot12_batch6_v1/ns180/baseline/videos/rank0-0-0_lora.mp4'
assert sha(parent) == summary['selected_original_sha256']
dest = target / 'results' / root.name / 'export_manifest.json'
dest.write_text(json.dumps({'files': files, 'actual_vlm_input_count': actual_inputs,
    'exported_evidence_images': len(required), 'omitted_derived_files': len(omitted),
    'reused_original': {'repository_path': str(parent.relative_to(target)), 'sha256': sha(parent)},
    'completed_candidate_videos': 1, 'interrupted_candidates': 1,
    'scope': 'Closed automatic development attempt; no retained improvement or completed policy pair.'}, indent=2) + '\n')
paths.append(str(dest.relative_to(target)))
(root.parent / 'native_ns180_automatic_export_paths.json').write_text(json.dumps(sorted(paths), indent=2) + '\n')
print(json.dumps({'paths': len(paths), 'bound_bytes': sum(x['bytes'] for x in files.values()), 'actual_vlm_inputs': actual_inputs}))
